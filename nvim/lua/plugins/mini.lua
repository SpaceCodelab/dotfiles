return {
	{
		"echasnovski/mini.nvim",
		version = false,

		config = function()
			-- ============================================================
			-- Comment
			-- ============================================================

			require("mini.comment").setup()

			-- ============================================================
			-- Move
			-- ============================================================

			require("mini.move").setup({
				mappings = {
					left = "<M-h>",
					right = "<M-l>",
					down = "<M-j>",
					up = "<M-k>",

					line_left = "<M-h>",
					line_right = "<M-l>",
					line_down = "<M-j>",
					line_up = "<M-k>",
				},
			})

			-- ============================================================
			-- Pairs
			-- ============================================================

			require("mini.pairs").setup()

			-- ============================================================
			-- Command line
			-- ============================================================

			require("mini.cmdline").setup()

			-- ============================================================
			-- File explorer
			-- ============================================================

			require("mini.files").setup({
				windows = {
					preview = true,
					width_focus = 30,
					width_preview = 50,
				},

				options = {
					use_as_default_explorer = true,
				},
			})

			-- ============================================================
			-- Notifications
			-- ============================================================

			require("mini.notify").setup({
				lsp_progress = {
					enable = true,
				},
			})

			-- ============================================================
			-- Statusline
			-- ============================================================

			require("mini.statusline").setup({
				use_icons = true,
			})

			-- ============================================================
			-- Starter screen
			-- ============================================================

			require("mini.starter").setup({
				header = "Neovim",
			})
		end,
	},
}
